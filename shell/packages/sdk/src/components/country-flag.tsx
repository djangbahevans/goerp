export function CountryFlag({ code, showName = false }: CountryFlagProps): ReactNode {
  const name = countryNameOf(code);
  // A code that's the wrong format, or the right format but has no
  // flag-icons entry, renders no flag glyph at all — just the raw code as
  // plain text — rather than a nonsensical or blank icon.
  const valid = VALID_CODE.test(code) && SUPPORTED_CODES.has(code.toUpperCase());
  return (
    <span className="inline-flex items-center gap-1">
      {valid ? (
        <span role="img" aria-label={name} className={`fi fi-${code.toLowerCase()}`} />
      ) : (
        <span role="img" aria-label={name}>
          {code}
        </span>
      )}
      {showName && <span className="text-sm">{name}</span>}
    </span>
  );
}
