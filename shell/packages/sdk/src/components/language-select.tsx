// Mirrors country-flag.tsx's countryNameOf pattern, for language tags
// instead of regions.
const LANGUAGE_NAMES = new Intl.DisplayNames(undefined, { type: "language" });

function languageNameOf(tag: string): string {
  try {
    return LANGUAGE_NAMES.of(tag.toLowerCase()) ?? tag;
  } catch {
    return tag;
  }
}

export function LanguageSelect({ id, value, onChange, placeholder, disabled }: LanguageSelectProps): ReactNode {
  return (
    <CodeSelect
      id={id}
      codes={LANGUAGE_CODES}
      nameOf={languageNameOf}
      renderRow={(_code, name) => <span>{name}</span>}
      value={value}
      onChange={onChange}
      placeholder={placeholder}
      disabled={disabled}
    />
  );
}
